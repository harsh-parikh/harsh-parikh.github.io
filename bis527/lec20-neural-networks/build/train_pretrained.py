"""Train the two pretrained models embedded in the deck.

1. Multinomial logistic regression (784 -> 10): the ten weight templates
   shown on the "Multinomial Logistic Regression" slide.
2. One-hidden-layer network (784 -> 64 ReLU -> 10): the forward-pass,
   draw-a-digit, and hidden-feature slides.

Both are trained on the full 60,000 MNIST training images with mini-batch
SGD + momentum and a small L2 penalty, evaluated on the 10,000 test images,
and written to js/pretrained.js as float32 base64. Seeds are fixed.

Run from the project root:  python3 build/train_pretrained.py
"""
import base64
import json
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from prepare_data import DATA, ROOT, read_images, read_labels  # noqa: E402

OUT = os.path.join(ROOT, "js", "pretrained.js")
SEED = 527
HIDDEN = 64


def softmax(z):
    z = z - z.max(axis=1, keepdims=True)
    e = np.exp(z)
    return e / e.sum(axis=1, keepdims=True)


def accuracy(p, y):
    return float((p.argmax(axis=1) == y).mean())


def train_logreg(xtr, ytr, xte, yte, rng, epochs=15, lr=0.5, batch=64, l2=1e-4):
    n, d = xtr.shape
    W = rng.normal(0, 0.01, size=(d, 10)).astype(np.float32)
    b = np.zeros(10, dtype=np.float32)
    Y = np.eye(10, dtype=np.float32)[ytr]
    for ep in range(epochs):
        perm = rng.permutation(n)
        for i in range(0, n, batch):
            idx = perm[i:i + batch]
            x, y = xtr[idx], Y[idx]
            p = softmax(x @ W + b)
            g = (p - y) / len(idx)
            W -= lr * (x.T @ g + l2 * W)
            b -= lr * g.sum(axis=0)
        acc = accuracy(softmax(xte @ W + b), yte)
        print(f"  logreg epoch {ep + 1:2d}  test acc {acc:.4f}")
    return W, b, acc


def train_mlp(xtr, ytr, xte, yte, rng, hidden=HIDDEN, epochs=20, lr=0.1,
              batch=64, l2=1e-4, momentum=0.9):
    n, d = xtr.shape
    W1 = (rng.normal(0, 1, size=(d, hidden)) * np.sqrt(2.0 / d)).astype(np.float32)
    b1 = np.zeros(hidden, dtype=np.float32)
    W2 = (rng.normal(0, 1, size=(hidden, 10)) * np.sqrt(2.0 / hidden)).astype(np.float32)
    b2 = np.zeros(10, dtype=np.float32)
    vel = [np.zeros_like(a) for a in (W1, b1, W2, b2)]
    Y = np.eye(10, dtype=np.float32)[ytr]
    for ep in range(epochs):
        perm = rng.permutation(n)
        for i in range(0, n, batch):
            idx = perm[i:i + batch]
            x, y = xtr[idx], Y[idx]
            z1 = x @ W1 + b1
            h = np.maximum(z1, 0)
            p = softmax(h @ W2 + b2)
            d2 = (p - y) / len(idx)
            gW2 = h.T @ d2 + l2 * W2
            gb2 = d2.sum(axis=0)
            d1 = (d2 @ W2.T) * (z1 > 0)
            gW1 = x.T @ d1 + l2 * W1
            gb1 = d1.sum(axis=0)
            for k, (par, g) in enumerate(zip((W1, b1, W2, b2), (gW1, gb1, gW2, gb2))):
                vel[k] = momentum * vel[k] - lr * g
                par += vel[k]
        h = np.maximum(xte @ W1 + b1, 0)
        acc = accuracy(softmax(h @ W2 + b2), yte)
        print(f"  mlp epoch {ep + 1:2d}  test acc {acc:.4f}")
    return W1, b1, W2, b2, acc


def main():
    t0 = time.time()
    rng = np.random.default_rng(SEED)
    xtr = read_images(os.path.join(DATA, "train-images-idx3-ubyte.gz")).astype(np.float32) / 255.0
    ytr = read_labels(os.path.join(DATA, "train-labels-idx1-ubyte.gz"))
    xte = read_images(os.path.join(DATA, "t10k-images-idx3-ubyte.gz")).astype(np.float32) / 255.0
    yte = read_labels(os.path.join(DATA, "t10k-labels-idx1-ubyte.gz"))
    print("logistic regression")
    W, b, acc_lr = train_logreg(xtr, ytr, xte, yte, rng)
    print("one-hidden-layer network")
    W1, b1, W2, b2, acc_mlp = train_mlp(xtr, ytr, xte, yte, rng)

    b64 = lambda a: base64.b64encode(np.ascontiguousarray(a, dtype=np.float32).tobytes()).decode("ascii")
    meta = {"seed": SEED, "hidden": HIDDEN, "logreg_test_acc": round(acc_lr, 4),
            "mlp_test_acc": round(acc_mlp, 4), "train_images": int(len(xtr)),
            "test_images": int(len(xte))}
    with open(OUT, "w") as f:
        f.write("// Generated by build/train_pretrained.py. float32 row-major, base64.\n")
        f.write(f"// meta: {json.dumps(meta)}\n")
        f.write("window.PRETRAINED = {\n")
        f.write(f"  meta: {json.dumps(meta)},\n")
        f.write(f'  logreg: {{ W: "{b64(W)}", b: "{b64(b)}", shape: [784, 10] }},\n')
        f.write(f'  mlp: {{ W1: "{b64(W1)}", b1: "{b64(b1)}", W2: "{b64(W2)}", b2: "{b64(b2)}", '
                f"hidden: {HIDDEN} }}\n")
        f.write("};\n")
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB", "in", round(time.time() - t0), "s")
    print(meta)


if __name__ == "__main__":
    main()
