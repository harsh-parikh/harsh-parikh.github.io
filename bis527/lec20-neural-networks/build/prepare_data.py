"""Prepare the MNIST subset embedded in the deck.

Reads the four IDX .gz files from ../data (downloaded from
https://storage.googleapis.com/cvdf-datasets/mnist/), takes the first
N_TRAIN training images and N_TEST test images, and writes js/mnist_data.js
as base64 uint8 so the deck loads from file:// without fetch().

Run from the project root:  python3 build/prepare_data.py
"""
import base64
import gzip
import os
import struct

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "js", "mnist_data.js")
N_TRAIN = 5000
N_TEST = 1000


def read_images(path):
    with gzip.open(path, "rb") as f:
        magic, n, rows, cols = struct.unpack(">IIII", f.read(16))
        assert magic == 2051, path
        buf = f.read(n * rows * cols)
    return np.frombuffer(buf, dtype=np.uint8).reshape(n, rows * cols)


def read_labels(path):
    with gzip.open(path, "rb") as f:
        magic, n = struct.unpack(">II", f.read(8))
        assert magic == 2049, path
        buf = f.read(n)
    return np.frombuffer(buf, dtype=np.uint8)


def main():
    xtr = read_images(os.path.join(DATA, "train-images-idx3-ubyte.gz"))[:N_TRAIN]
    ytr = read_labels(os.path.join(DATA, "train-labels-idx1-ubyte.gz"))[:N_TRAIN]
    xte = read_images(os.path.join(DATA, "t10k-images-idx3-ubyte.gz"))[:N_TEST]
    yte = read_labels(os.path.join(DATA, "t10k-labels-idx1-ubyte.gz"))[:N_TEST]
    b64 = lambda a: base64.b64encode(np.ascontiguousarray(a).tobytes()).decode("ascii")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by build/prepare_data.py. MNIST subset, uint8, base64.\n")
        f.write("// Source: Yann LeCun, Corinna Cortes, Christopher J.C. Burges, "
                "The MNIST database of handwritten digits.\n")
        f.write("window.MNIST_RAW = {\n")
        f.write(f"  nTrain: {N_TRAIN}, nTest: {N_TEST}, side: 28,\n")
        f.write(f'  trainX: "{b64(xtr)}",\n')
        f.write(f'  trainY: "{b64(ytr)}",\n')
        f.write(f'  testX: "{b64(xte)}",\n')
        f.write(f'  testY: "{b64(yte)}"\n')
        f.write("};\n")
    print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB")
    print("train label counts", np.bincount(ytr, minlength=10).tolist())
    print("test label counts", np.bincount(yte, minlength=10).tolist())


if __name__ == "__main__":
    main()
